// site-generator-speed-01: a faster drop-in for makefun-site 1.0.0.
//
// Same answers as makefun-site 1.0.0, byte for byte, for every input — the
// pipeline below re-implements its build (front matter, permalinks, Markdown,
// collections, tags, layouts, report) with the same rules and the same report
// strings, only faster:
//
//   - Markdown is lexed and rendered in one fused pass (no token objects);
//     inline rendering copies plain runs in chunks instead of escaping one
//     character at a time, and the block checks are hand-rolled char tests
//     instead of a regex per line.
//   - slugify skips NFKD for pure-ASCII text (ASCII is fixed under NFKD)
//     and memoises per build; front matter is parsed by hand, not regexes.
//   - Templates render into one shared string array instead of building a
//     fresh string per node; lookups walk the same scope chain.
//   - Cards are built once per post and reused by page objects.
//
// Nothing is cached from one case to the next: every cache is created fresh
// inside run(). No dependencies, no WASM, no native code, deterministic.

const REPORT_FILE = 'build-report.txt';
const RESERVED = ['posts', 'tags', 'page'];

// ------------------------------------------------------------------ text

const ESC_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_TEST = /[&<>"']/;
const ESC_RE = /[&<>"']/g;
function escapeHtml(text) {
  return ESC_TEST.test(text) ? text.replace(ESC_RE, (c) => ESC_MAP[c]) : text;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
function longDate(date) {
  const y = date.slice(0, 4);
  const m = Number(date.slice(5, 7));
  const d = Number(date.slice(8, 10));
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

const ASCII_RE = /^[\x00-\x7F]*$/;
const MARKS_RE = /\p{M}/gu;
/** slugify, with a per-build memo. Pure-ASCII text skips NFKD (identity on ASCII). */
function makeSlugify() {
  const cache = new Map();
  return function slugify(text) {
    let out = cache.get(text);
    if (out !== undefined) return out;
    const plain = ASCII_RE.test(text) ? text : text.normalize('NFKD').replace(MARKS_RE, '');
    let s = '';
    let gap = false;
    for (let i = 0; i < plain.length; i++) {
      const ch = plain[i];
      let keep = null;
      if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
      else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
      if (keep === null) {
        gap = s.length > 0;
        continue;
      }
      if (gap) s += '-';
      gap = false;
      s += keep;
    }
    s = s.slice(0, 64);
    let e = s.length;
    while (e > 0 && s[e - 1] === '-') e--;
    if (e < s.length) s = s.slice(0, e);
    out = s === '' ? 'untitled' : s;
    cache.set(text, out);
    return out;
  };
}

function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

// ------------------------------------------------------------------ front matter

const KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function isLowerKeyChar(c) {
  return (c >= 'a' && c <= 'z') || c === '_';
}

/** A string value: "..." with \" and \\ its only escapes, or bare. */
function stringOf(raw) {
  if (raw[0] === '"') {
    if (raw.length < 2 || raw[raw.length - 1] !== '"') return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw[0] === '[') return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      // YYYY-MM-DD, a real day from 1970-01-01 to 2099-12-31.
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      let y = 0, mo = 0, d = 0;
      if (ok) {
        for (let i = 0; i < 10; i++) {
          if (i === 4 || i === 7) continue;
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) { ok = false; break; }
        }
      }
      if (ok) {
        y = (raw.charCodeAt(0) - 48) * 1000 + (raw.charCodeAt(1) - 48) * 100 + (raw.charCodeAt(2) - 48) * 10 + (raw.charCodeAt(3) - 48);
        mo = (raw.charCodeAt(5) - 48) * 10 + (raw.charCodeAt(6) - 48);
        d = (raw.charCodeAt(8) - 48) * 10 + (raw.charCodeAt(9) - 48);
        if (y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) ok = false;
      }
      if (!ok) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      for (const t of tags) {
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1) {
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      if (raw.length === 0) return { error: 'key "layout": not a template name' };
      for (let i = 0; i < raw.length; i++) {
        const c = raw[i];
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) return { error: 'key "layout": not a template name' };
      }
      return { value: raw };
    }
    case 'slug': {
      if (raw.length === 0 || raw.length > 64) return { error: 'key "slug": not a slug' };
      let ok = true;
      let prevDash = false;
      for (let i = 0; i < raw.length; i++) {
        const c = raw[i];
        if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) { prevDash = false; continue; }
        if (c === '-' && !prevDash && i !== 0) { prevDash = true; continue; }
        ok = false;
        break;
      }
      if (!ok || prevDash) return { error: 'key "slug": not a slug' };
      return { value: raw };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

function isBlankLine(line) {
  for (let i = 0; i < line.length; i++) {
    if (line[i] !== ' ' && line[i] !== '\t') return false;
  }
  return true;
}

/** Parse front matter: { data, body } or { error }, first reason first. */
function parseFrontMatter(text) {
  // First line must be exactly '---'.
  if (text !== '---' && !text.startsWith('---\n')) return { error: 'no front matter' };
  // Scan the front-matter lines only; the body is the slice after the close.
  const fmLines = [];
  let pos = 4; // just past '---\n'
  let lineNo = 2;
  let closeEnd = -1;
  while (pos <= text.length) {
    const nl = text.indexOf('\n', pos);
    const end = nl === -1 ? text.length : nl;
    const line = text.slice(pos, end);
    if (line === '---') { closeEnd = end; break; }
    fmLines.push(line);
    if (nl === -1) break;
    pos = nl + 1;
    lineNo++;
  }
  if (closeEnd === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let idx = 0; idx < fmLines.length; idx++) {
    const line = fmLines[idx];
    const n = idx + 2;
    if (isBlankLine(line) || line[0] === '#') continue;
    let k = 0;
    while (k < line.length && isLowerKeyChar(line[k])) k++;
    if (k === 0 || line[k] !== ':') return { error: `line ${n} is not "key: value"` };
    const key = line.slice(0, k);
    let raw;
    if (k + 1 === line.length) raw = '';
    else if (line[k + 1] === ' ') raw = line.slice(k + 2);
    else return { error: `line ${n} is not "key: value"` };
    let e = raw.length;
    while (e > 0 && (raw[e - 1] === ' ' || raw[e - 1] === '\t')) e--;
    if (e < raw.length) raw = raw.slice(0, e);
    if (!KEYS.has(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  const body = closeEnd === text.length ? '' : text.slice(closeEnd + 1);
  return { data, body };
}

// ------------------------------------------------------------------ markdown

const ESCAPABLE = new Uint8Array(128);
for (const c of ['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']) ESCAPABLE[c.charCodeAt(0)] = 1;

function findUnescaped(s, what, from) {
  let p = s.indexOf(what, from);
  while (p !== -1) {
    let k = p - 1, n = 0;
    while (k >= from && s[k] === '\\') { n++; k--; }
    if (n % 2 === 0) return p;
    p = s.indexOf(what, p + 1);
  }
  return -1;
}

function findSingleStar(s, from) {
  let p = s.indexOf('*', from);
  while (p !== -1) {
    let k = p - 1, n = 0;
    while (k >= from && s[k] === '\\') { n++; k--; }
    if (n % 2 === 1) { p = s.indexOf('*', p + 1); continue; }
    if (s[p + 1] === '*') { p = s.indexOf('*', p + 2); continue; }
    return p;
  }
  return -1;
}

const WS_RE = /\s/;
function isSpaceCode(code) {
  return code === 9 || code === 10 || code === 11 || code === 12 || code === 13 || code === 32 ||
    code === 160 || code === 5760 || (code >= 8192 && code <= 8202) || code === 8232 || code === 8233 ||
    code === 8239 || code === 8287 || code === 12288 || code === 65279;
}

/** Inline rendering into `out` (a string array). `link` resolves a link target. */
function inline(s, link, out) {
  const len = s.length;
  let i = 0;
  while (i < len) {
    // next special char among \ ` * [
    let j = len;
    let k;
    k = s.indexOf('\\', i); if (k !== -1 && k < j) j = k;
    k = s.indexOf('`', i); if (k !== -1 && k < j) j = k;
    k = s.indexOf('*', i); if (k !== -1 && k < j) j = k;
    k = s.indexOf('[', i); if (k !== -1 && k < j) j = k;
    if (j > i) out.push(escapeHtml(s.slice(i, j)));
    if (j >= len) break;
    i = j;
    const c = s[i];
    if (c === '\\' && i + 1 < len && ESCAPABLE[s.charCodeAt(i + 1)] === 1) {
      out.push(escapeHtml(s[i + 1])); // '>' is escapable AND HTML-special: \> is &gt;
      i += 2;
      continue;
    }
    if (c === '\\') { out.push('\\'); i++; continue; }
    if (c === '`') {
      const jj = s.indexOf('`', i + 1);
      if (jj > i + 1) {
        out.push('<code>', escapeHtml(s.slice(i + 1, jj)), '</code>');
        i = jj + 1;
      } else {
        out.push('`');
        i++;
      }
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const jj = findUnescaped(s, '**', i + 2);
        if (jj > i + 2) {
          out.push('<strong>');
          inline(s.slice(i + 2, jj), link, out);
          out.push('</strong>');
          i = jj + 2;
        } else {
          out.push('**');
          i += 2;
        }
        continue;
      }
      const jj = findSingleStar(s, i + 1);
      if (jj > i + 1) {
        out.push('<em>');
        inline(s.slice(i + 1, jj), link, out);
        out.push('</em>');
        i = jj + 1;
      } else {
        out.push('*');
        i++;
      }
      continue;
    }
    // c === '['
    const kk = findUnescaped(s, ']', i + 1);
    const m = kk !== -1 && s[kk + 1] === '(' ? s.indexOf(')', kk + 2) : -1;
    const target = m === -1 ? '' : s.slice(kk + 2, m);
    if (target !== '' && !WS_RE.test(target)) {
      out.push('<a href="', escapeHtml(link(target)), '">');
      inline(s.slice(i + 1, kk), link, out);
      out.push('</a>');
      i = m + 1;
      continue;
    }
    out.push('[');
    i++;
  }
}

function inlineStr(s, link) {
  const out = [];
  inline(s, link, out);
  return out.join('');
}

function trimLine(line) {
  let a = 0, b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** A heading line's { depth, text } or null. */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line[h] === '#') h++;
  if (h === 0 || h > 6) return null;
  if (line[h] !== ' ' && line[h] !== '\t') return null;
  let a = h;
  while (a < line.length && (line[a] === ' ' || line[a] === '\t')) a++;
  let b = line.length;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  if (b === a) return null;
  return { depth: h, text: line.slice(a, b) };
}

/** Whether `line` is a fence opening; returns its language or null. */
function fenceOpen(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return null;
  let j = 3;
  while (j < line.length) {
    const c = line[j];
    if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-') j++;
    else break;
  }
  for (; j < line.length; j++) {
    if (line[j] !== ' ' && line[j] !== '\t') return null;
  }
  return line.slice(3, j);
}

function fenceClose(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return false;
  for (let j = 3; j < line.length; j++) {
    if (line[j] !== ' ' && line[j] !== '\t') return false;
  }
  return true;
}

function isHr(line) {
  if (line !== '---' && line !== '***') {
    if (!line.startsWith('---') && !line.startsWith('***')) return false;
    const head = line.slice(0, 3);
    if (head !== '---' && head !== '***') return false;
    for (let j = 3; j < line.length; j++) {
      if (line[j] !== ' ' && line[j] !== '\t') return false;
    }
    return true;
  }
  return true;
}

function endsParagraph(line) {
  return isBlankLine(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

function isContinued(line) {
  if (line[0] !== ' ' || line[1] !== ' ') return false;
  let k = 0;
  while (k < line.length && line[k] === ' ') k++;
  return k >= 2 && k < line.length && !isSpaceCode(line.charCodeAt(k));
}

/**
 * Render a body: { html, toc, excerpt }. Fused lex+render — no token objects.
 * `link` resolves link targets; `slugify`/`uniqueSlug` share the build's memo.
 */
function renderMarkdown(src, link, slugify) {
  const lines = src.split('\n');
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlankLine(line)) { i++; continue; }
    const lang = fenceOpen(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < n && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${lang}"`;
      let code = `<pre><code${cls}>`;
      for (const l of body) code += `${escapeHtml(l)}\n`;
      blocks.push(`${code}</code></pre>`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inlineStr(heading.text, link);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      blocks.push('<hr>');
      i++;
      continue;
    }
    if (line[0] === '>') {
      const body = [];
      while (i < n && lines[i][0] === '>') body.push(lines[i++].replace(/^> ?/, ''));
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      if (kept.length === 0) blocks.push('<blockquote>\n</blockquote>');
      else blocks.push(`<blockquote>\n<p>${inlineStr(kept.join('\n'), link)}</p>\n</blockquote>`);
      continue;
    }
    // list?
    let isOrdered = false;
    let start = 1;
    let firstText = null;
    if ((line[0] === '-' || line[0] === '*') && line[1] === ' ') {
      firstText = line.slice(2);
    } else {
      let d = 0;
      while (d < line.length && line[d] >= '0' && line[d] <= '9') d++;
      if (d >= 1 && d <= 9 && line[d] === '.' && line[d + 1] === ' ') {
        isOrdered = true;
        start = Number(line.slice(0, d));
        firstText = line.slice(d + 2);
      }
    }
    if (firstText !== null) {
      const items = [[trimLine(firstText)]];
      i++;
      while (i < n) {
        const l = lines[i];
        let m = null;
        if (isOrdered) {
          let d = 0;
          while (d < l.length && l[d] >= '0' && l[d] <= '9') d++;
          if (d >= 1 && d <= 9 && l[d] === '.' && l[d + 1] === ' ') m = l.slice(d + 2);
        } else if ((l[0] === '-' || l[0] === '*') && l[1] === ' ') {
          m = l.slice(2);
        }
        if (m !== null) {
          items.push([trimLine(m)]);
          i++;
        } else if (isContinued(l)) {
          items[items.length - 1].push(trimLine(l));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let out = `${open}\n`;
      for (const parts of items) out += `<li>${inlineStr(parts.join('\n'), link)}</li>\n`;
      blocks.push(`${out}</${tag}>`);
      continue;
    }
    // paragraph
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inlineStr(body.join('\n'), link);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  let html = '';
  for (const b of blocks) html += `${b}\n`;
  return { html, toc, excerpt: excerpt ?? '' };
}

